/// Bump when the provenance header format changes in a way that alters the
/// generated bytes. The version is part of the header so a deployed artifact
/// generated by an older binary fails byte-equality against a newer generator
/// and is regenerated rather than silently trusted.
pub const GENERATOR_FORMAT_VERSION: u32 = 1;

/// First line of every generated runtime config. `verify_live_config` and the
/// `generate` guard match on this exact prefix.
pub const GENERATED_MARKER_PREFIX: &str = GENERATED_LIVE_CONFIG_MARKER_PREFIX;

const MAX_PROFILE_ID_LEN: usize = 63;
const PROFILES_DIR_NAME: &str = "profiles";
const ROOT_CONFIG_FILE_NAME: &str = "root.toml";
pub const LIVE_CONFIG_FILE_NAME: &str = "live.toml";
const PROFILE_OVERLAY_SUFFIX: &str = ".overlay.toml";
const STRATEGIES_DIR_NAME: &str = "strategies";
const STRATEGY_CONFIG_EXTENSION: &str = "toml";

/// Opaque production profile selector. This is not a path: it is the only
/// operator-controlled input that derives a tracked overlay path.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct ProfileId(String);

impl ProfileId {
    pub fn parse(raw: &str) -> Result<Self, ProfileError> {
        if !is_valid_profile_id(raw) {
            return Err(ProfileError::InvalidProfileId(raw.to_string()));
        }
        Ok(Self(raw.to_string()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// Typed production overlay: the ONLY production deltas against the shared base
/// template. Everything not named here is single-sourced in the base config. The
/// `#[serde(deny_unknown_fields)]` makes a typo (or a stale/removed field) fail
/// loudly at parse time rather than silently widening the deployed config.
#[derive(Debug, Clone, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct ProdOverlay {
    /// REPLACES `base.strategy_files` wholesale.
    pub strategy_files: Vec<String>,
    /// The subset of `base.clients` to KEEP in the composed config; every other
    /// client block in the base is dropped. Composition errors if any name here
    /// is absent from `base.clients`.
    pub active_clients: Vec<String>,
    /// The subset of `base.realized_volatility_surfaces` to KEEP. Composition
    /// errors if any name here is absent from the base surfaces.
    pub active_rv_surfaces: Vec<String>,
    /// Per-surface scalar overrides merged into that surface's `[policy]` table.
    /// Each key MUST appear in `active_rv_surfaces`. Required (no serde default):
    /// an overlay that overrides no RV policy must declare `rv_policy_overrides = {}`
    /// explicitly — a silent default on a production surface is forbidden (fail loud).
    pub rv_policy_overrides: BTreeMap<String, toml::Table>,
    /// The full `[risk.loss_governor]` block, inserted at `risk.loss_governor` in
    /// the composed config. Absent from the base; the overlay owns the explicit
    /// loss-governor policy state.
    pub loss_governor: toml::Table,
    /// Per-client FULL replacement of `[clients.<name>.execution]`. Each key MUST
    /// appear in `active_clients`. A full replace lets the overlay both override
    /// values (funder, signature_type) and DROP placeholder sub-tables
    /// (e.g. `on_chain_collateral`) without an explicit delete directive. Required
    /// (no serde default): an overlay that replaces no client execution must declare
    /// `client_execution = {}` explicitly — a silent default on a production surface
    /// is forbidden (fail loud).
    pub client_execution: BTreeMap<String, toml::Table>,
}

/// Outcome of generating a runtime config from a tracked overlay.
#[derive(Debug, Clone, serde::Serialize)]
pub struct GeneratedLiveConfig {
    /// Opaque source profile ID selected by the operator.
    pub source_profile: String,
    /// `config_bundle_checksum` of the COMPOSED config (composed root text +
    /// strategy files). Recorded in the header and reproducible from
    /// overlay ⊕ base alone.
    pub profile_bundle_sha256: String,
    /// Production invariants confirmed before generation.
    pub invariants: ProductionInvariants,
    /// Full runtime config text: provenance header (comments) + composed body.
    pub text: String,
}

/// Result of verifying a deployed runtime config against its source overlay+base.
#[derive(Debug, Clone, serde::Serialize)]
pub struct LiveConfigVerification {
    pub profile_id: String,
    pub profile_path: PathBuf,
    pub deployed_path: PathBuf,
    pub profile_bundle_sha256: String,
    /// Production invariants re-confirmed on the *deployed* file.
    pub invariants: ProductionInvariants,
    /// True once byte-equality and the independent binary load both passed.
    pub matches_profile: bool,
    pub loads_against_binary: bool,
}

/// The production-readiness facts `generate`/`verify` confirm and report. Values
/// (e.g. the loss-rail amounts, which strategy is selected) are decided by the
/// overlay and the pilot-config issues, not by this module — it only proves the
/// rails and selection are present and fails closed when they are not.
#[derive(Debug, Clone, serde::Serialize)]
pub struct ProductionInvariants {
    pub strategy_files: Vec<String>,
    pub loss_governor_present: bool,
    pub loss_governor_enabled: bool,
    pub max_per_trade_loss: String,
    pub max_daily_loss: String,
    pub max_rolling_loss: String,
    pub max_drawdown: String,
    pub default_max_notional_per_order: String,
}

/// Errors from generating or verifying a runtime config. All are fail-closed:
/// generation and verification only succeed when every check passes.
#[derive(Debug)]
pub enum ProfileError {
    /// The composed config (or deployed file) did not load against this binary's
    /// schema + semantic validation. This is the staleness guard.
    Load {
        path: PathBuf,
        source: BoltV3ConfigError,
    },
    /// Filesystem error reading or writing an overlay, base, or deployed file.
    Io { path: PathBuf, message: String },
    /// The overlay text was not valid TOML / not a valid [`ProdOverlay`].
    Overlay { path: PathBuf, message: String },
    /// The profile selector is not an opaque lowercase ASCII profile ID.
    InvalidProfileId(String),
    /// The overlay referenced a base/client/surface that the composition could not
    /// satisfy (e.g. an `active_clients` name absent from the base).
    Composition(String),
    /// A required production invariant was missing (e.g. no loss-governor block).
    Invariant(String),
    /// A deployed file did not match the config regenerated from the overlay+base.
    Mismatch(String),
    /// `generate` was pointed at a file that is itself already a generated
    /// runtime config rather than a source overlay.
    AlreadyGenerated(PathBuf),
}

impl std::fmt::Display for ProfileError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ProfileError::Load { path, source } => {
                write!(
                    f,
                    "config `{}` does not load against this binary: {source}",
                    path.display()
                )
            }
            ProfileError::Io { path, message } => {
                write!(f, "failed to read `{}`: {message}", path.display())
            }
            ProfileError::Overlay { path, message } => {
                write!(f, "overlay `{}` is invalid: {message}", path.display())
            }
            ProfileError::InvalidProfileId(profile_id) => write!(
                f,
                "profile `{profile_id}` is invalid; set BOLT_LIVE_PROFILE to an opaque lowercase \
                 ASCII profile ID (1-63 chars, starting with a letter or digit, using only \
                 letters, digits, '-' or '_'), not a path"
            ),
            ProfileError::Composition(message) => write!(f, "{message}"),
            ProfileError::Invariant(message) => write!(f, "{message}"),
            ProfileError::Mismatch(message) => write!(f, "{message}"),
            ProfileError::AlreadyGenerated(path) => write!(
                f,
                "`{}` is already a generated runtime config; pass the source overlay instead",
                path.display()
            ),
        }
    }
}

impl std::error::Error for ProfileError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            ProfileError::Load { source, .. } => Some(source),
            _ => None,
        }
    }
}

fn read_config_text(path: &Path) -> Result<String, ProfileError> {
    crate::bounded_config_read::read_to_string(path).map_err(|source| ProfileError::Io {
        path: path.to_path_buf(),
        message: source.to_string(),
    })
}

fn canonical_config_root(config_root: &Path) -> Result<PathBuf, ProfileError> {
    reject_symlink_path(config_root, "config root")?;
    std::fs::canonicalize(config_root).map_err(|source| ProfileError::Io {
        path: config_root.to_path_buf(),
        message: source.to_string(),
    })
}

fn reject_symlink_path(path: &Path, context: &str) -> Result<(), ProfileError> {
    let metadata = std::fs::symlink_metadata(path).map_err(|source| ProfileError::Io {
        path: path.to_path_buf(),
        message: source.to_string(),
    })?;
    if metadata.file_type().is_symlink() {
        return Err(ProfileError::Composition(format!(
            "{context} `{}` must not be a symbolic link",
            path.display()
        )));
    }
    Ok(())
}

fn is_valid_profile_id(raw: &str) -> bool {
    if raw.is_empty() || raw.len() > MAX_PROFILE_ID_LEN {
        return false;
    }
    if matches!(raw, "live" | "local" | "root" | "profiles") {
        return false;
    }
    let mut bytes = raw.bytes();
    let Some(first) = bytes.next() else {
        return false;
    };
    if !(first.is_ascii_lowercase() || first.is_ascii_digit()) {
        return false;
    }
    bytes.all(|byte| {
        byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-' || byte == b'_'
    })
}

fn validate_production_strategy_files(
    config_root: &Path,
    strategy_files: &[String],
) -> Result<(), ProfileError> {
    let strategies_dir = config_root.join(STRATEGIES_DIR_NAME);
    reject_symlink_path(&strategies_dir, "strategy_files directory")?;
    let canonical_strategies_dir = std::fs::canonicalize(&strategies_dir).map_err(|source| {
        ProfileError::Composition(format!(
            "strategy_files requires `{}` to exist and be readable: {source}",
            strategies_dir.display()
        ))
    })?;

    for configured in strategy_files {
        validate_production_strategy_file(
            config_root,
            &canonical_strategies_dir,
            configured.as_str(),
        )?;
    }
    Ok(())
}

fn validate_production_strategy_file(
    config_root: &Path,
    canonical_strategies_dir: &Path,
    configured: &str,
) -> Result<(), ProfileError> {
    if configured.is_empty() || configured.trim() != configured {
        return Err(strategy_file_error(
            configured,
            "must be a non-empty trimmed relative path under `strategies/`",
        ));
    }
    if configured.contains('\\') {
        return Err(strategy_file_error(
            configured,
            "must use `/` path separators and stay under `strategies/`",
        ));
    }

    let path = Path::new(configured);
    if path.is_absolute() {
        return Err(strategy_file_error(
            configured,
            "must be relative and stay under `strategies/`",
        ));
    }

    let components: Vec<std::path::Component<'_>> = path.components().collect();
    if components.len() < 2 {
        return Err(strategy_file_error(
            configured,
            "must name a TOML file under `strategies/`",
        ));
    }
    if !matches!(
        components.first(),
        Some(std::path::Component::Normal(first))
            if *first == std::ffi::OsStr::new(STRATEGIES_DIR_NAME)
    ) {
        return Err(strategy_file_error(
            configured,
            "must start with `strategies/`",
        ));
    }
    if components
        .iter()
        .any(|component| !matches!(component, std::path::Component::Normal(_)))
    {
        return Err(strategy_file_error(
            configured,
            "must not contain `.`, `..`, root, or prefix components",
        ));
    }
    if path.extension().and_then(|extension| extension.to_str()) != Some(STRATEGY_CONFIG_EXTENSION)
    {
        return Err(strategy_file_error(
            configured,
            "must name a `.toml` strategy config",
        ));
    }

    let candidate = config_root.join(path);
    let canonical_candidate = std::fs::canonicalize(&candidate).map_err(|source| {
        strategy_file_error(
            configured,
            &format!("must resolve to an existing readable file: {source}"),
        )
    })?;
    if !canonical_candidate.starts_with(canonical_strategies_dir) {
        return Err(strategy_file_error(
            configured,
            "must resolve inside the configured `strategies/` directory",
        ));
    }
    let metadata = std::fs::metadata(&canonical_candidate).map_err(|source| {
        strategy_file_error(
            configured,
            &format!("must resolve to a readable regular file: {source}"),
        )
    })?;
    if !metadata.is_file() {
        return Err(strategy_file_error(
            configured,
            "must resolve to a regular file",
        ));
    }

    Ok(())
}

fn strategy_file_error(configured: &str, message: &str) -> ProfileError {
    ProfileError::Composition(format!("strategy_files entry `{configured}` {message}"))
}

pub fn profile_overlay_path(config_root: &Path, profile_id: &ProfileId) -> PathBuf {
    let mut file_name = profile_id.as_str().to_string();
    file_name.push_str(PROFILE_OVERLAY_SUFFIX);
    config_root.join(PROFILES_DIR_NAME).join(file_name)
}

pub fn root_config_path(config_root: &Path) -> PathBuf {
    config_root.join(ROOT_CONFIG_FILE_NAME)
}

pub fn live_config_path(config_root: &Path) -> PathBuf {
    config_root.join(LIVE_CONFIG_FILE_NAME)
}

/// Parse and validate the overlay text into a [`ProdOverlay`].
fn parse_overlay(overlay_path: &Path, overlay_text: &str) -> Result<ProdOverlay, ProfileError> {
    toml::from_str(overlay_text).map_err(|error| ProfileError::Overlay {
        path: overlay_path.to_path_buf(),
        message: error.to_string(),
    })
}

/// Borrow the `[table]` named `key` inside `parent`, erroring if it is missing or
/// not a table. Used to navigate the base config during composition.
fn require_table<'a>(
    parent: &'a toml::Table,
    key: &str,
    context: &str,
) -> Result<&'a toml::Table, ProfileError> {
    match parent.get(key) {
        Some(toml::Value::Table(table)) => Ok(table),
        Some(_) => Err(ProfileError::Composition(format!(
            "{context}: base key `{key}` must be a table"
        ))),
        None => Err(ProfileError::Composition(format!(
            "{context}: base is missing required table `{key}`"
        ))),
    }
}

/// Compose the deterministic composed-config TOML text from the overlay and the
/// derived base. Pure function of the on-disk bytes — identical input ⇒ identical
/// output, so the deployed artifact is reproducible and byte-comparable.
fn compose_config_text(config_root: &Path, overlay: &ProdOverlay) -> Result<String, ProfileError> {
    let base_path = root_config_path(config_root);
    reject_symlink_path(&base_path, "base root.toml")?;
    let base_text = read_config_text(&base_path)?;
    let mut root: toml::Table = toml::from_str(&base_text).map_err(|error| {
        ProfileError::Composition(format!(
            "base config `{}` is not valid TOML: {error}",
            base_path.display()
        ))
    })?;

    // (b) strategy_files: wholesale replace, fenced to the reviewed strategy bundle.
    validate_production_strategy_files(config_root, &overlay.strategy_files)?;
    root.insert(
        "strategy_files".to_string(),
        toml::Value::Array(
            overlay
                .strategy_files
                .iter()
                .map(|path| toml::Value::String(path.clone()))
                .collect(),
        ),
    );

    // (c) clients: retain only active_clients, then full-replace each named
    // [clients.<name>.execution].
    let base_clients = require_table(&root, "clients", "active_clients")?.clone();
    let mut retained_clients = toml::Table::new();
    for name in &overlay.active_clients {
        let client = base_clients.get(name).ok_or_else(|| {
            ProfileError::Composition(format!(
                "active_clients references `{name}`, which is not present in base.clients"
            ))
        })?;
        retained_clients.insert(name.clone(), client.clone());
    }
    for (name, execution) in &overlay.client_execution {
        let client = retained_clients.get_mut(name).ok_or_else(|| {
            ProfileError::Composition(format!(
                "client_execution references `{name}`, which is not in active_clients"
            ))
        })?;
        let client_table = client.as_table_mut().ok_or_else(|| {
            ProfileError::Composition(format!("base client `{name}` must be a table"))
        })?;
        client_table.insert(
            "execution".to_string(),
            toml::Value::Table(execution.clone()),
        );
    }
    root.insert("clients".to_string(), toml::Value::Table(retained_clients));

    // (d) realized_volatility_surfaces: retain only active_rv_surfaces, then merge
    // per-surface rv_policy_overrides into that surface's [policy].
    let base_surfaces =
        require_table(&root, "realized_volatility_surfaces", "active_rv_surfaces")?.clone();
    let active_surface_names: BTreeSet<&str> = overlay
        .active_rv_surfaces
        .iter()
        .map(String::as_str)
        .collect();
    let mut retained_surfaces = toml::Table::new();
    for name in &overlay.active_rv_surfaces {
        let surface = base_surfaces.get(name).ok_or_else(|| {
            ProfileError::Composition(format!(
                "active_rv_surfaces references `{name}`, which is not present in \
                 base.realized_volatility_surfaces"
            ))
        })?;
        retained_surfaces.insert(name.clone(), surface.clone());
    }
    for (name, overrides) in &overlay.rv_policy_overrides {
        if !active_surface_names.contains(name.as_str()) {
            return Err(ProfileError::Composition(format!(
                "rv_policy_overrides references surface `{name}`, which is not in active_rv_surfaces"
            )));
        }
        let surface = retained_surfaces
            .get_mut(name)
            .and_then(toml::Value::as_table_mut)
            .ok_or_else(|| {
                ProfileError::Composition(format!("retained surface `{name}` must be a table"))
            })?;
        let policy = surface
            .entry("policy".to_string())
            .or_insert_with(|| toml::Value::Table(toml::Table::new()))
            .as_table_mut()
            .ok_or_else(|| {
                ProfileError::Composition(format!("surface `{name}` [policy] must be a table"))
            })?;
        for (override_key, override_value) in overrides {
            policy.insert(override_key.clone(), override_value.clone());
        }
    }
    root.insert(
        "realized_volatility_surfaces".to_string(),
        toml::Value::Table(retained_surfaces),
    );

    // (e) risk.loss_governor: insert the overlay's full block.
    let risk = root
        .get_mut("risk")
        .and_then(toml::Value::as_table_mut)
        .ok_or_else(|| {
            ProfileError::Composition("base is missing required table `risk`".to_string())
        })?;
    risk.insert(
        "loss_governor".to_string(),
        toml::Value::Table(overlay.loss_governor.clone()),
    );

    // (f) serialize deterministically: rebuild every table with keys inserted in
    // sorted order so the emitted bytes are identical regardless of the `toml`
    // crate's map backing (`preserve_order` on or off).
    let sorted = sort_toml_value(toml::Value::Table(root));
    toml::to_string(&sorted).map_err(|error| {
        ProfileError::Composition(format!("composed config failed to serialize: {error}"))
    })
}

/// Recursively rebuild a [`toml::Value`] so every table's keys are in sorted
/// order. With insertion-ordered map backing this yields deterministic output;
/// with `BTreeMap` backing the keys are already sorted, so the result is identical
/// either way. The serializer's own table-vs-scalar ordering is a deterministic
/// function of this input, so the emitted bytes are stable run-to-run.
fn sort_toml_value(value: toml::Value) -> toml::Value {
    match value {
        toml::Value::Table(table) => {
            let mut sorted = toml::Table::new();
            let mut entries: Vec<(String, toml::Value)> = table.into_iter().collect();
            entries.sort_by(|left, right| left.0.cmp(&right.0));
            for (key, child) in entries {
                sorted.insert(key, sort_toml_value(child));
            }
            toml::Value::Table(sorted)
        }
        toml::Value::Array(items) => {
            toml::Value::Array(items.into_iter().map(sort_toml_value).collect())
        }
        scalar => scalar,
    }
}

/// Load the composed config text through the binary's real loader, WITHOUT
/// mutating the repo tree. The composed text and referenced strategy files are
/// copied into a fresh private temp directory, so the loader resolves strategy
/// files exactly as deployed `live.toml` does (relative to the loaded file's
/// parent) while preserving the production no-symlink invariant. The temp
/// directory is removed before returning, on success and on error alike.
fn load_composed_against_binary(
    config_root: &Path,
    overlay_path: &Path,
    overlay: &ProdOverlay,
    composed_text: &str,
) -> Result<(LoadedBoltV3Config, ProductionInvariants), ProfileError> {
    let temp_dir = ComposeTempDir::create()?;
    for relative in &overlay.strategy_files {
        let source = config_root.join(relative);
        let dest = temp_dir.path().join(relative);
        if let Some(parent) = dest.parent() {
            std::fs::create_dir_all(parent).map_err(|source| ProfileError::Io {
                path: parent.to_path_buf(),
                message: source.to_string(),
            })?;
        }
        std::fs::copy(&source, &dest).map_err(|source| ProfileError::Io {
            path: dest,
            message: source.to_string(),
        })?;
    }

    let composed_path = temp_dir.path().join("composed-live.toml");
    crate::bolt_v3_atomic_io::write_atomic_file_with_mode(
        &composed_path,
        composed_text.as_bytes(),
        crate::bolt_v3_atomic_io::RUNTIME_CONFIG_FILE_MODE,
    )
    .map_err(|error| ProfileError::Io {
        path: error.path,
        message: error.source.to_string(),
    })?;

    let loaded = load_bolt_v3_config(&composed_path).map_err(|source| ProfileError::Load {
        path: overlay_path.to_path_buf(),
        source,
    })?;
    let invariants = confirm_production_invariants(&loaded)?;
    Ok((loaded, invariants))
    // `temp_dir` drops here, removing the staged directory on success and error alike.
}

/// A uniquely-named private temp directory for staging the composed config during
/// the validation load. Removed on drop so neither `config/` nor the temp root is
/// left littered, even if the load errors. The unique path identity is owned by
/// [`crate::bolt_v3_atomic_io::unique_temp_path`] (one counter for all temp paths).
struct ComposeTempDir {
    path: PathBuf,
}

impl ComposeTempDir {
    fn create() -> Result<Self, ProfileError> {
        let path = crate::bolt_v3_atomic_io::unique_temp_path(COMPOSE_TEMP_DIR_PREFIX);
        std::fs::create_dir_all(&path).map_err(|source| ProfileError::Io {
            path: path.clone(),
            message: source.to_string(),
        })?;
        Ok(Self { path })
    }

    fn path(&self) -> &Path {
        &self.path
    }
}

const COMPOSE_TEMP_DIR_PREFIX: &str = "bolt-v2-compose";

impl Drop for ComposeTempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.path);
    }
}

/// Confirm the production invariants the live deploy depends on, failing closed
/// when any is absent. Reused by both generation (on the composed config) and
/// verification (on the deployed file).
pub fn confirm_production_invariants(
    loaded: &LoadedBoltV3Config,
) -> Result<ProductionInvariants, ProfileError> {
    if loaded.root.strategy_files.is_empty() {
        return Err(ProfileError::Invariant(
            "production profile declares no strategy_files".to_string(),
        ));
    }
    let config_root = loaded.root_path.parent().ok_or_else(|| {
        ProfileError::Invariant(format!(
            "production config `{}` must have a parent config root",
            loaded.root_path.display()
        ))
    })?;
    validate_production_strategy_files(config_root, &loaded.root.strategy_files)?;

    let governor = loaded.root.risk.loss_governor.as_ref().ok_or_else(|| {
        ProfileError::Invariant(
            "production profile must declare [risk.loss_governor] before live deploy".to_string(),
        )
    })?;

    let max_per_trade_loss = governor.max_per_trade_loss.clone().ok_or_else(|| {
        ProfileError::Invariant(
            "[risk.loss_governor].max_per_trade_loss must be set before live deploy".to_string(),
        )
    })?;
    let max_daily_loss = governor.max_daily_loss.clone().ok_or_else(|| {
        ProfileError::Invariant(
            "[risk.loss_governor].max_daily_loss must be set before live deploy".to_string(),
        )
    })?;
    let max_rolling_loss = governor.max_rolling_loss.clone().ok_or_else(|| {
        ProfileError::Invariant(
            "[risk.loss_governor].max_rolling_loss must be set before live deploy".to_string(),
        )
    })?;
    let max_drawdown = governor.max_drawdown.clone().ok_or_else(|| {
        ProfileError::Invariant(
            "[risk.loss_governor].max_drawdown must be set before live deploy".to_string(),
        )
    })?;

    Ok(ProductionInvariants {
        strategy_files: loaded.root.strategy_files.clone(),
        loss_governor_present: true,
        loss_governor_enabled: governor.enabled,
        max_per_trade_loss,
        max_daily_loss,
        max_rolling_loss,
        max_drawdown,
        default_max_notional_per_order: loaded.root.risk.default_max_notional_per_order.clone(),
    })
}

fn provenance_header(source_profile: &str, profile_bundle_sha256: &str) -> String {
    format!(
        "{GENERATED_MARKER_PREFIX}{GENERATOR_FORMAT_VERSION}\n\
         # source_profile={source_profile}\n\
         # profile_bundle_sha256={profile_bundle_sha256}\n\
         # Generated by `bolt-v2 ops generate-live-config`; DO NOT EDIT.\n\
         # Edit the tracked source overlay (or base root.toml) in a reviewed PR, then regenerate (issue #768).\n\
         \n"
    )
}

/// The product of composing + loading an overlay: the composed body text (no
/// header) and the load of that body against this binary.
struct ComposedConfig {
    text: String,
    loaded: LoadedBoltV3Config,
    invariants: ProductionInvariants,
}

/// Compose, validate, and produce the runtime config from a tracked overlay,
/// without stamping the provenance header. Shared by [`generate_live_config`] and
/// [`verify_live_config`] so both compose identically.
fn compose_and_load(
    config_root: &Path,
    raw_profile_id: &str,
) -> Result<ComposedConfig, ProfileError> {
    let profile_id = ProfileId::parse(raw_profile_id)?;
    let config_root = canonical_config_root(config_root)?;
    reject_symlink_path(&config_root.join(PROFILES_DIR_NAME), "profiles directory")?;
    let overlay_path = profile_overlay_path(&config_root, &profile_id);
    reject_symlink_path(&overlay_path, "profile overlay")?;
    let overlay_text = read_config_text(&overlay_path)?;
    if overlay_text.contains(GENERATED_MARKER_PREFIX) {
        return Err(ProfileError::AlreadyGenerated(overlay_path.to_path_buf()));
    }
    let overlay = parse_overlay(&overlay_path, &overlay_text)?;
    let composed_text = compose_config_text(&config_root, &overlay)?;
    let (loaded, invariants) =
        load_composed_against_binary(&config_root, &overlay_path, &overlay, &composed_text)?;
    Ok(ComposedConfig {
        text: composed_text,
        loaded,
        invariants,
    })
}

/// Generate a deterministic, provenance-stamped runtime config from a tracked
/// production overlay composed onto the derived base. Fails closed on any TOML,
/// schema, semantic, composition, or production-invariant problem.
pub fn generate_live_config(
    config_root: &Path,
    raw_profile_id: &str,
) -> Result<GeneratedLiveConfig, ProfileError> {
    let profile_id = ProfileId::parse(raw_profile_id)?;
    let composed = compose_and_load(config_root, profile_id.as_str())?;

    let header = provenance_header(profile_id.as_str(), &composed.loaded.config_bundle_checksum);
    let text = format!("{header}{}", composed.text);

    Ok(GeneratedLiveConfig {
        source_profile: profile_id.as_str().to_string(),
        profile_bundle_sha256: composed.loaded.config_bundle_checksum,
        invariants: composed.invariants,
        text,
    })
}

/// Verify that a deployed runtime config is exactly what the approved overlay+base
/// compose to AND still loads against this binary. Both must hold.
pub fn verify_live_config(
    config_root: &Path,
    raw_profile_id: &str,
) -> Result<LiveConfigVerification, ProfileError> {
    let profile_id = ProfileId::parse(raw_profile_id)?;
    let config_root = canonical_config_root(config_root)?;
    let profile_path = profile_overlay_path(&config_root, &profile_id);
    let deployed_path = live_config_path(&config_root);
    reject_symlink_path(&deployed_path, "deployed live.toml")?;
    let generated = generate_live_config(&config_root, profile_id.as_str())?;
    let deployed_text = read_config_text(&deployed_path)?;

    // Byte-parity against the freshly-composed artifact is the single mechanism that
    // proves the deployed config has not diverged — INCLUDING the content of every
    // referenced strategy file. `generate` stamps a provenance header embedding
    // `config_bundle_checksum`, a hash over the composed root body PLUS every strategy
    // file's text (see `config_bundle_checksum` in `bolt_v3_config`), and re-reads the
    // on-box strategy files. So a deployed strategy file that diverges (valid schema,
    // but different sizing/feeds/stale) recomputes a different checksum, changes the
    // regenerated header, and fails this check — even though strategy_files are
    // referenced by path and their bytes are not otherwise in the compared text. A
    // separate file-vs-file strategy comparison would be redundant with this, and inert
    // in the production single-tree layout where the derived root and the deployed
    // `live.toml` resolve strategy paths to the same on-box files.
    if deployed_text != generated.text {
        return Err(ProfileError::Mismatch(format!(
            "deployed runtime config `{}` does not match the config composed from overlay `{}`; \
             re-run `ops generate-live-config` and redeploy rather than hand-editing",
            deployed_path.display(),
            profile_path.display()
        )));
    }

    // Independently load the deployed file through the binary. Byte-equality
    // proves provenance; this proves the bytes still satisfy the live schema.
    let deployed_loaded =
        load_bolt_v3_config(&deployed_path).map_err(|source| ProfileError::Load {
            path: deployed_path.to_path_buf(),
            source,
        })?;
    let invariants = confirm_production_invariants(&deployed_loaded)?;

    Ok(LiveConfigVerification {
        profile_id: profile_id.as_str().to_string(),
        profile_path,
        deployed_path,
        profile_bundle_sha256: generated.profile_bundle_sha256,
        invariants,
        matches_profile: true,
        loads_against_binary: true,
    })
}
