//! Tracked production-overlay → runtime `live.toml` composition and verification (issue #768).
//!
//! ## Problem this closes
//!
//! The live runtime config (`config/live.toml`) and its operator source
//! (`config/live.local.toml`) were gitignored and hand-maintained. They were
//! therefore invisible to CI and drifted silently against the deployed binary's
//! schema. On 2026-06-18 a BTC pilot start failed at `systemd` time because the
//! hand-edited config carried a stale key (`nautilus.data_engine
//! .graceful_shutdown_on_error`) the current binary no longer accepts — and
//! hash parity between local and EC2 did not catch it, because both copies were
//! equally stale.
//!
//! ## Single, fail-closed, composed path
//!
//! The fix makes the production config a *tracked* artifact and gives it one
//! generation + verification path. To avoid duplicating ~580 lines of shared
//! infrastructure, the production config is expressed as a typed OVERLAY selected
//! by an opaque profile ID. The ID derives
//! `<config-root>/profiles/<profile-id>.overlay.toml`, and the shared base is
//! always `<config-root>/root.toml`. The overlay declares ONLY the pilot deltas
//! ([`ProdOverlay`]); generation composes (base ⊕ overlay) into the runtime config.
//!
//! * [`generate_live_config`] parses the derived overlay, composes it onto the
//!   derived base, serializes the result deterministically, loads the composed config
//!   through the SAME [`load_bolt_v3_config`] the binary uses at startup, enforces
//!   the production invariants a live deploy requires (a tracked loss-governor
//!   block with explicit enablement state and a non-empty strategy selection), and
//!   emits a deterministic, provenance-stamped runtime config. Any
//!   schema, semantic, composition, or invariant error fails generation closed.
//! * [`verify_live_config`] re-composes from the on-box (overlay ⊕ base) and proves
//!   `<config-root>/live.toml` is (a) byte-identical to the regenerated artifact and
//!   (b) still loads against this exact binary. The regenerated artifact's provenance
//!   header embeds `config_bundle_checksum` — a hash over the composed root body PLUS
//!   every referenced strategy file's content — and generation re-reads the on-box
//!   strategy files, so (a) also catches a divergent deployed strategy file even though
//!   strategy_files are referenced by path and their bytes are not otherwise in the
//!   compared text. The independent load in (b) is the staleness guard — byte parity
//!   alone cannot catch a key the current binary has dropped.
//!
//! `verify_live_config` covers the config-identity half of pre-arm. The full
//! launch gate chains it inside `ops launch` with secret checks, live secret
//! resolution, storage prestart, reference-current-price health, and the run-loop
//! start (see `deploy/README.md`). The single source of truth is the base template
//! plus the tracked overlay selected by profile ID; the base owns the shared
//! infrastructure blocks and the overlay owns the pilot deltas, so neither is
//! duplicated. The production systemd unit runs `ops launch` as `ExecStart`, so
//! the load-against-this-binary check runs on the bytes actually present on the
//! box at the live entry point, not advisory.
//!
//! ## What ties the deployed config to the reviewed revision
//!
//! The deployed config is bound to the PR-reviewed Git revision *procedurally*:
//! deploy tooling regenerates `live.toml` from the tracked overlay+base rather than
//! hand-editing the deployed file, and `verify` proves the deployed bytes are
//! exactly what the on-box overlay+base compose to and still load against this
//! binary. No profile is baked into the binary — a binary-embedded release anchor
//! does not scale to a multi-strategy/venue fleet and is superseded by arming bound
//! to the deployed config checksum plus a signed release manifest (#768 follow-up).
//!
//! The composed config is a complete [`BoltV3RootConfig`], so schema currency is
//! enforced by the real parser (`#[serde(deny_unknown_fields)]`), not a parallel
//! one — there is no second config format and no second code path. The overlay
//! itself is typed with `#[serde(deny_unknown_fields)]`, so an overlay typo fails
//! loudly. The provenance header is emitted as TOML *comments*: a non-comment
//! metadata key would be rejected by `deny_unknown_fields`.

use std::{
    collections::{BTreeMap, BTreeSet},
    path::{Path, PathBuf},
};

